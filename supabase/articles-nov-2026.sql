## Why do gums bleed?

Throughout the day, a sticky film of bacteria forms on your teeth. Dentists call it plaque.

Plaque is normal, but it needs to be removed regularly.

When it collects around the edges of your gums, it can irritate them. Your gums become inflamed, meaning they may look red, feel swollen, or bleed easily.

This early stage of gum disease is called *gingivitis*.

Don't let the name frighten you. It simply means gum inflammation.

The encouraging news is that gingivitis can usually be reversed with effective daily cleaning and appropriate dental care.

The problem is what happens when we ignore it.

In some people, untreated gum inflammation progresses to a more serious form of gum disease that damages the tissues and bone holding teeth in place.

At that stage, the damage may not be fully reversible.

## Could I simply be brushing too hard?

Absolutely.

Brushing aggressively, especially with a hard toothbrush, can injure your gums.

But there's an interesting catch.

When people notice bleeding, they sometimes stop brushing the affected area because they're afraid of making things worse.

Unfortunately, if plaque is causing the inflammation, avoiding the area allows more bacteria to accumulate.

The solution is usually not to stop cleaning.

It's to clean gently and properly.

Think of your gums like delicate skin. You want to take care of them, not scrub them as though you're cleaning a stubborn stain from a cooking pot.

## What can you do at home?

Start with a soft-bristled toothbrush.

Brush twice daily for about two minutes, paying attention to the area where your teeth meet your gums.

You don't need to apply excessive pressure.

Gentle, controlled movements work better than aggressive scrubbing.

Next, clean between your teeth once a day.

Your toothbrush cannot easily reach every narrow space between neighbouring teeth. Dental floss or small interdental brushes help remove plaque from these areas.

If you're new to flossing, your gums may bleed initially, especially if they're already inflamed. Be gentle and give yourself time to learn the correct technique.

If the bleeding continues, arrange a dental examination rather than assuming it will eventually stop.

And remember, plaque sometimes hardens into something called tartar.

Once that happens, normal brushing won't remove it. You'll need a professional dental cleaning.

